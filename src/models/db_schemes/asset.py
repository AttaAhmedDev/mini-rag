from dataclasses import field
from pydantic import BaseModel, Field, ConfigDict, field_validator
from typing import Optional
from bson import ObjectId
from datetime import datetime

class Asset(BaseModel):
    id : Optional[ObjectId] = Field(default=None, alias="_id")# id is optional as it is generated by the database in mongodb
    asset_project_id: ObjectId
    asset_type: str = Field(...,min_length=1) #... is Elipsis operator which means the field is required and must be a string with a minimum length of 1
    asset_name: str = Field(...,min_length=1)
    asset_size: int = Field(gt=0,default=None)
    asset_config: dict = Field(default=None)
    asset_created_at: datetime = Field(default=datetime.now())
    
    model_config = ConfigDict(
        #arbitrary_types_allowed=True is used to allow arbitrary types to be used in the model like (ObjectId)
        #populate_by_name=True is used to deal with the attribute name in two different ways like (id, _id)
        arbitrary_types_allowed=True,
        populate_by_name=True,
    )
    
    @classmethod
    def get_indexes(cls):
        return [
            {
                "key":[("asset_project_id",1)],
                "name":"asset_project_id_index",
                "unique":False,
            },
            {
                "key":[("asset_project_id",1),("asset_name",1)],
                "name":"asset_project_id_asset_name_index",
                "unique":True
            }
        ]